/**
 * Pixel-art sprite registry. Each sprite is a list of filled unit squares on a
 * 16x16 grid, rendered as <rect> elements with shape-rendering:crispEdges so it
 * stays sharp at any zoom. Sprites inherit currentColor, so light and dark pixel
 * theme work without duplicate assets.
 *
 * Deliberately partial: any name absent here falls back to its lucide icon via
 * PixelIcon, so the set can grow without a flag day.
 *
 * The art is authored as 16x16 ASCII grids and mechanically transcribed to the
 * coordinate arrays below — every sprite's grid is reproduced in the block
 * comment above it, so a reviewer can see the shape without decoding the pairs.
 * Rows run top-to-bottom (y = 0 is the top row, matching the SVG viewBox) and
 * left-to-right within a row, one grid row per source line so the coordinates
 * line up with the picture. That layout is why the object below carries a
 * `prettier-ignore`: prettier would put every coordinate pair on its own line
 * and destroy the correspondence.
 *
 * `alert-triangle` and `triangle-alert` are the same lucide glyph under its old
 * and new names; both are registered with identical art so callers on either
 * name get the sprite.
 */
